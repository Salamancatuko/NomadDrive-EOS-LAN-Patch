#include <atomic>
#include <cstdint>
#include <mutex>
#include "Log.h"

namespace {
std::mutex g_missing_log_mutex;

void log_missing_call(const char* name, std::atomic<bool>& logged)
{
    if (logged.load(std::memory_order_acquire))
        return;
    std::lock_guard<std::mutex> lock(g_missing_log_mutex);
    if (logged.load(std::memory_order_relaxed))
        return;
    logged.store(true, std::memory_order_release);
    APP_LOG(Log::LogLevel::WARN, "[MISSING_EXPORT] %s called (stubbed, returning 0)", name);
}
} // namespace

